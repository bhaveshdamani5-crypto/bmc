// Usage (from repo root):  node supabase/seed/build-seed.mjs
// Generates supabase/seed.sql from menu.mjs. Re-run after editing menu.mjs.
// DEV DATA ONLY: table tokens below are predictable on purpose. Never seed production with them.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { categories } from './menu.mjs';

const here = dirname(fileURLToPath(import.meta.url));

// Deterministic UUIDs so re-seeding is stable and tests can reference known ids.
const uuid = (key) => {
  const h = createHash('md5').update(key).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const b = (x) => (x == null ? 'null' : x ? 'true' : 'false');
const paise = (r) => Math.round(r * 100);
const n = (x) => (x == null ? 'null' : String(x));

const BREW = uuid('restaurant:brew-moon');
const DEMO2 = uuid('restaurant:demo-cafe-two');

const out = [];
const push = (s) => out.push(s);

push('-- GENERATED by supabase/seed/build-seed.mjs. Do not edit by hand; edit menu.mjs and re-run.');
push('-- DEV DATA ONLY.');
push('begin;');

// ---- restaurants
push(`insert into restaurants (id, slug, name, phone, address, tax_rate_bps, prices_include_tax, status, trial_ends_at) values
  (${q(BREW)}, 'brew-moon', 'The Brew Moon Cafe', null, 'NRI Layout, Bengaluru', 500, true, 'trial', now() + interval '14 days'),
  (${q(DEMO2)}, 'demo-cafe-two', 'Demo Cafe Two', null, 'Test address', 500, true, 'trial', now() + interval '14 days');`);
push(`insert into subscriptions (restaurant_id, plan, status) values (${q(BREW)}, 'starter', 'trialing'), (${q(DEMO2)}, 'starter', 'trialing');`);

// ---- tables (dev tokens are predictable on purpose)
const tableRows = [];
for (let i = 1; i <= 10; i++) {
  const label = `T${i}`;
  tableRows.push(`  (${q(uuid(`table:brew:${label}`))}, ${q(BREW)}, ${q(label)}, ${q(`devtoken-brew-${String(i).padStart(2, '0')}`)})`);
}
for (let i = 1; i <= 3; i++) {
  const label = `T${i}`;
  tableRows.push(`  (${q(uuid(`table:demo2:${label}`))}, ${q(DEMO2)}, ${q(label)}, ${q(`devtoken-demo2-${String(i).padStart(2, '0')}`)})`);
}
push(`insert into tables (id, restaurant_id, label, token) values\n${tableRows.join(',\n')};`);

// ---- menu (Brew Moon)
const cats = [], items = [], variants = [], groups = [], mods = [];
let itemCount = 0;

categories.forEach((cat, ci) => {
  const catId = uuid(`cat:${cat.name}`);
  cats.push(`  (${q(catId)}, ${q(BREW)}, ${q(cat.name)}, ${q(cat.tagline)}, ${(ci + 1) * 10})`);

  cat.items.forEach((it, ii) => {
    itemCount++;
    const itemId = uuid(`item:${cat.name}:${it.n}`);
    let base, cal, veg;
    if (it.vars) {
      base = Math.min(...it.vars.map((x) => x.p));
      const allVeg = it.vars.every((x) => x.v === true);
      const allNon = it.vars.every((x) => x.v === false);
      veg = allVeg ? true : allNon ? false : null;
      cal = null;
    } else {
      base = it.p; cal = it.c; veg = it.v;
    }
    items.push(`  (${q(itemId)}, ${q(BREW)}, ${q(catId)}, ${q(it.n)}, ${q(it.d ?? null)}, ${paise(base)}, ${n(cal)}, ${b(veg)}, ${(ii + 1) * 10})`);

    (it.vars ?? []).forEach((x, vi) => {
      variants.push(`  (${q(uuid(`var:${itemId}:${x.n}`))}, ${q(BREW)}, ${q(itemId)}, ${q(x.n)}, ${paise(x.p - base)}, ${n(x.c)}, ${b(x.v)}, ${(vi + 1) * 10})`);
    });

    (it.mods ?? []).forEach((g, gi) => {
      const gid = uuid(`grp:${itemId}:${g.g}`);
      groups.push(`  (${q(gid)}, ${q(BREW)}, ${q(itemId)}, ${q(g.g)}, ${g.min}, ${g.max}, ${(gi + 1) * 10})`);
      g.o.forEach(([name, extra], oi) => {
        mods.push(`  (${q(uuid(`mod:${gid}:${name}`))}, ${q(BREW)}, ${q(gid)}, ${q(name)}, ${paise(extra)}, ${(oi + 1) * 10})`);
      });
    });
  });
});

push(`insert into categories (id, restaurant_id, name, tagline, sort_order) values\n${cats.join(',\n')};`);
push(`insert into items (id, restaurant_id, category_id, name, description, base_price_paise, calories, is_veg, sort_order) values\n${items.join(',\n')};`);
push(`insert into item_variants (id, restaurant_id, item_id, name, price_delta_paise, calories, is_veg, sort_order) values\n${variants.join(',\n')};`);
push(`insert into modifier_groups (id, restaurant_id, item_id, name, min_select, max_select, sort_order) values\n${groups.join(',\n')};`);
push(`insert into modifiers (id, restaurant_id, group_id, name, price_delta_paise, sort_order) values\n${mods.join(',\n')};`);

// ---- tiny menu for the second cafe (used by tenant-isolation tests)
const d2cat = uuid('cat:demo2:Coffee');
push(`insert into categories (id, restaurant_id, name, sort_order) values (${q(d2cat)}, ${q(DEMO2)}, 'Coffee', 10);`);
push(`insert into items (id, restaurant_id, category_id, name, base_price_paise, is_veg, sort_order) values
  (${q(uuid('item:demo2:Cappuccino'))}, ${q(DEMO2)}, ${q(d2cat)}, 'Cappuccino', 15000, true, 10),
  (${q(uuid('item:demo2:Espresso'))}, ${q(DEMO2)}, ${q(d2cat)}, 'Espresso', 10000, true, 20);`);

push('commit;');

const file = join(here, '..', 'seed.sql');
writeFileSync(file, out.join('\n') + '\n');
console.log(`seed.sql written: ${itemCount} items, ${variants.length} variants, ${groups.length} modifier groups, ${mods.length} modifiers`);
